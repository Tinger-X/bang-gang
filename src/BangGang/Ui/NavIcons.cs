    private static readonly Dictionary<NavIcon, GraphicsPath> Cache = new();
    private static readonly object Gate = new();

    /// <summary>
    /// 一枚图标的形状，坐标在 1024×1024 的 viewBox 里。
    /// **返回的是缓存对象，调用方别改它** —— 要缩放就照 <see cref="Draw"/> 克隆一份再变换。
    ///
    /// 按图标缓存：一份 SVG 里好几条 path、拼起来几百个点，而左栏每重绘一次就要画六枚。
    /// </summary>
    private static GraphicsPath Shape(NavIcon icon)
    {
        lock (Gate)
        {
            if (Cache.TryGetValue(icon, out var cached)) return cached;

            var path = new GraphicsPath { FillMode = FillMode.Winding };
            foreach (string d in Paths(icon))
            {
                try { path.AddPath(SvgPath.Parse(d), connect: false); }
                catch (Exception ex) { Trace.Log($"icon {icon}: path failed {ex.Message}"); }
            }
            Cache[icon] = path;
            return path;
        }
    }

    /// <summary>这枚图标在 1024 网格里的实际外框（离屏探针用它核对归一化）。</summary>
    public static RectangleF Bounds(NavIcon icon) => Shape(icon).GetBounds();

    /// <summary>
    /// 把图标画进 <paramref name="box"/>（按**实际外框**等比铺满并居中），填充色为
    /// <paramref name="color"/>。
    ///
    /// 按外框而不是按 viewBox 归一：这几张图的画布虽然都是 1024，但墨迹占的比例差很多
    /// （有的铺满、有的只占八成），照 viewBox 铺会让它们并排看着大小不一。
    /// </summary>
    public static void Draw(Graphics g, NavIcon icon, RectangleF box, Color color)
    {
        var raw = Shape(icon);
        if (raw.PointCount == 0) return;

        var src = raw.GetBounds();
        if (src.Width <= 0 || src.Height <= 0) return;

        float k = Math.Min(box.Width / src.Width, box.Height / src.Height);
        float ox = box.X + (box.Width - src.Width * k) / 2f - src.X * k;
        float oy = box.Y + (box.Height - src.Height * k) / 2f - src.Y * k;

        using var scaled = (GraphicsPath)raw.Clone();
        using (var m = new Matrix())
        {
            m.Translate(ox, oy);
            m.Scale(k, k);
            scaled.Transform(m);
        }
        using var brush = new SolidBrush(color);
        g.FillPath(brush, scaled);
    }
